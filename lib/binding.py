"""ROUTING-BINDING.md: rendered on every run from the shipped roles and [binding] (spec R14).

The person's entries live in routewise.toml [binding], which routewise never writes after
the first run, so an update can show an approval as pending but can never approve.
"""

import re

from roles import Role
from settings import Binding

PREFIX = "<!-- generated by routewise from "
VERSION = re.compile(r"^Version (\d+), ", re.MULTILINE)
NEEDS_APPROVAL = "frontier"  # rules spec section 12: a role on this tier is Ask first


class BindingError(Exception):
    """The binding cannot be rendered: a bad rules spec or an impossible approval."""


def marker(template: str, install: str) -> str:
    """The first line of a generated binding, naming its sources and how to change it."""
    return (
        f"{PREFIX}{template} and routewise.toml [binding]; "
        f"edit routewise.toml and re-run {install} -->"
    )


def is_generated(text: str) -> bool:
    """routewise wrote this binding: its first line is the marker (spec S3)."""
    return text.startswith(PREFIX)


def rules_version(spec: str) -> int:
    """The rules spec's version, from its `Version N, <date>` line."""
    found = VERSION.search(spec)
    if not found:
        raise BindingError("spec/SPEC-model-routing.md has no version line (Version N, date)")
    return int(found.group(1))


def status(binding: Binding, version: int) -> str:
    """'' when the shipped version is approved, else 'pending' or 'not recorded'."""
    if binding.approved_rules_version > version:
        raise BindingError(
            f"routewise.toml: [binding] approved_rules_version {binding.approved_rules_version} "
            f"is newer than the shipped rules spec (version {version}); set it to {version}"
        )
    if binding.approved_rules_version == 0:
        return "not recorded"
    return "" if binding.approved_rules_version == version else "pending"


def approval_line(binding: Binding, version: int) -> str:
    state = status(binding, version)
    if state == "not recorded":
        return (
            "**Approval not recorded.** Fill in `[binding]` in `routewise.toml` "
            f"(`approved_rules_version = {version}`) and re-run."
        )
    by = binding.approved_by or "_name not recorded_"
    on = binding.approved_on or "_date not recorded_"
    line = f"Approved by {by} on {on} for rules spec version {binding.approved_rules_version}."
    if state == "pending":
        line += (
            f" **Approval pending:** rules spec version {version} "
            f"(approved: {binding.approved_rules_version})."
        )
    return line


def role_rows(roles: list[Role], state: str) -> str:
    """One table row per role: its tier and effort, and the approval state on frontier."""
    rows = []
    for role in roles:
        effort = "the harness's default effort" if role.effort == "default" else f"`{role.effort}`"
        note = f" (approval {state})" if state and role.tier == NEEDS_APPROVAL else ""
        rows.append(f"| `{role.name}` | `{role.tier}` at {effort}{note} |")
    return "\n".join(rows)


def render(
    template: str, values: dict[str, str], roles: list[Role], binding: Binding, version: int
) -> str:
    """The whole binding: marker, approval, the fixed rows, one row per role."""
    state = status(binding, version)
    review = (
        f"First review on {binding.review_from}, then monthly."
        if binding.review_from
        else "_Not recorded._"
    )
    filled = {
        **values,
        "{{marker}}": marker(values["{{template}}"], values["{{install}}"]),
        "{{approval}}": approval_line(binding, version),
        "{{assistant_pins}}": binding.assistant_pins or "_Not recorded._",
        "{{review}}": review,
        "{{role_rows}}": role_rows(roles, state),
    }
    text = template
    for key, value in filled.items():
        text = text.replace(key, value)
    return text
