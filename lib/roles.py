"""Neutral role files (roles/*.md) and their rendering for one harness.

A role file is Markdown with a frontmatter block holding only `name`, `description` (one line
or a folded block), `tools`, `tier`, `effort` and `skills` (spec R8). Any other key is
refused, so a role cannot carry permissions, hooks or servers into the generated agent, and no
YAML library is needed.
Roles are read-only (spec R-A1): `write` and `edit` tools are refused here and per harness.
"""

import re
from dataclasses import dataclass
from pathlib import Path

KEY = re.compile(r"^(name|tier|effort|tools|skills):[ \t]*(.*?)[ \t]*$")
DESCRIPTION = re.compile(r"^description:")
CONTINUATION = re.compile(r"^[ \t]+\S")
TOKEN = re.compile(r"^[A-Za-z0-9._-]{1,64}$")
TIERS = ("fast", "balanced", "deep", "frontier")
READ_ONLY_TOOLS = ("read", "search", "shell", "web")
# The only harness tool names a role may get: read-only tools of each harness (spec R-A1).
# An allowlist, not a denylist, so a new or MCP write tool can never slip in.
ALLOWED_TOOLS = {
    "cc": frozenset({"Read", "Glob", "Grep", "Bash", "WebSearch", "WebFetch"}),
    "agy": frozenset(
        {"view_file", "list_dir", "find_by_name", "grep_search", "run_command"}
        | {"search_web", "read_url_content"}
    ),
}
# A model name or alias: letters, digits and . _ - : [ ] only, so it cannot add a line.
MODEL = re.compile(r"^[A-Za-z0-9._:\[\]-]{1,80}$")
# A skill name: `name` or `plugin:name`, lower-case letters, digits and -, so it cannot carry a
# path, a space or another frontmatter line (spec R8, S6). Claude Code preloads at most 32.
SKILL = re.compile(r"[a-z0-9][a-z0-9-]{0,63}(:[a-z0-9][a-z0-9-]{0,63})?")  # fullmatch
# A stand-in's agent name (spec R9): a file name too, so no path, no `:` and no space.
STAND_IN = re.compile(r"[a-z0-9][a-z0-9-]{0,63}")  # fullmatch
MAX_SKILLS = 32
MARKER = "# generated by routewise from {source}; edit that file and re-run {command}"
# A stand-in names its own file after `as` (spec R9); a role's marker stays as above.
AS = " as "
MARKER_LINE = re.compile(r"^---\r?\n# generated by routewise from (.+?); edit that file")


class RoleError(Exception):
    """A role file that cannot be read or rendered."""


@dataclass(frozen=True)
class Role:
    source: Path
    name: str
    tier: str
    effort: str  # "default" when the file sets none
    tools: tuple[str, ...]
    description: tuple[str, ...]  # the description line and its continuation lines
    body: str
    skills: tuple[str, ...] = ()  # what to check; the body still fixes behaviour (spec R8)


@dataclass(frozen=True)
class Harness:
    key: str
    dir: str
    tools: dict[str, list[str]]
    tiers: dict[str, str]  # empty: the harness cannot set a model per agent
    efforts: tuple[str, ...]


def split_front(path: Path) -> tuple[list[str], str]:
    text = path.read_text(encoding="utf-8")
    parts = text.split("---\n", 2)
    if len(parts) != 3 or parts[0] != "":
        raise RoleError(f"{path}: no frontmatter block")
    return parts[1].splitlines(), parts[2]


def parse_tools(path: Path, value: str) -> tuple[str, ...]:
    if not (value.startswith("[") and value.endswith("]")):
        raise RoleError(f"{path}: tools must be a list such as [read, search]")
    tools = tuple(t.strip() for t in value[1:-1].split(",") if t.strip())
    if not tools:
        # An empty tools line gives a Claude Code agent every tool, write tools included.
        raise RoleError(f"{path}: tools is empty; list at least one, such as [read]")
    for tool in tools:
        if tool not in READ_ONLY_TOOLS:
            allowed = ", ".join(READ_ONLY_TOOLS)
            reason = f"roles are read-only ({allowed})"
            raise RoleError(f"{path}: tool {tool!r} is not allowed; {reason}")
    return tools


def skill_names(label: str, names: list[str]) -> tuple[str, ...]:
    """Checked skill names; `label` names the file or setting in the error."""
    for name in names:
        if not SKILL.fullmatch(name):
            raise RoleError(f"{label}: skill name {name!r} must be name or plugin:name in a-z0-9-")
    for name in names:
        if names.count(name) > 1:
            raise RoleError(f"{label}: skill name {name!r} is listed twice")
    if len(names) > MAX_SKILLS:
        raise RoleError(f"{label}: at most {MAX_SKILLS} skills; list fewer")
    return tuple(names)


def parse_skills(path: Path, value: str) -> tuple[str, ...]:
    if not (value.startswith("[") and value.endswith("]")):
        raise RoleError(f"{path}: skills must be a list such as [plugin:skill]")
    return skill_names(str(path), [s.strip() for s in value[1:-1].split(",") if s.strip()])


def sort_lines(path: Path, lines: list[str]) -> tuple[dict[str, str], list[str]]:
    """The single-line keys, and the description lines; anything else is refused."""
    keys: dict[str, str] = {}
    description: list[str] = []
    for line in lines:
        key = KEY.match(line)
        if key:
            keys[key.group(1)] = key.group(2)
        elif DESCRIPTION.match(line) or (description and CONTINUATION.match(line)):
            description.append(line)
        elif line.strip():
            raise RoleError(f"{path}: frontmatter line {line!r} is not allowed in a role")
    return keys, description


def checked(path: Path, keys: dict[str, str]) -> dict[str, str]:
    for needed in ("name", "tier", "tools"):
        if needed not in keys:
            raise RoleError(f"{path}: the frontmatter has no {needed}")
    for single in ("name", "effort"):
        if single in keys and not TOKEN.match(keys[single]):
            raise RoleError(f"{path}: {single} {keys[single]!r} must be one word")
    if keys["tier"] not in TIERS:
        raise RoleError(f"{path}: unknown tier {keys['tier']!r}; use one of {', '.join(TIERS)}")
    return keys


def read_role(path: Path) -> Role:
    lines, body = split_front(path)
    keys, description = sort_lines(path, lines)
    keys = checked(path, keys)
    return Role(
        source=path,
        name=keys["name"],
        tier=keys["tier"],
        effort=keys.get("effort", "default"),
        tools=parse_tools(path, keys["tools"]),
        description=tuple(description),
        body=body,
        skills=parse_skills(path, keys.get("skills", "[]")),
    )


def read_roles(folder: Path) -> list[Role]:
    roles = [read_role(path) for path in sorted(folder.glob("*.md"))]
    if not roles:
        raise RoleError(f"{folder}: no role files")
    return roles


def harness_tools(role: Role, harness: Harness) -> list[str]:
    allowed = ALLOWED_TOOLS.get(harness.key, frozenset())
    names: list[str] = []
    for tool in role.tools:
        if tool not in harness.tools:
            raise RoleError(f"{role.source}: tool {tool!r} has no {harness.key} name")
        for name in harness.tools[tool]:
            if name not in allowed:
                raise RoleError(f"harness.toml: {harness.key} {tool} maps to {name!r}, not allowed")
            names.append(name)
    if not names:
        raise RoleError(f"{role.source}: no {harness.key} tools; an empty list means every tool")
    return names


def model_lines(role: Role, harness: Harness) -> list[str]:
    """`model:` and `effort:` lines, or none for a harness that cannot set them."""
    if not harness.tiers:
        return []
    model = harness.tiers.get(role.tier, "")
    if not MODEL.match(model):
        raise RoleError(f"harness.toml: {harness.key} tier {role.tier} must be a model name")
    lines = [f"model: {model}"]
    if role.effort != "default":
        if role.effort not in harness.efforts:
            offered = f"is not offered by {harness.key}"
            raise RoleError(f"{role.source}: effort {role.effort!r} {offered}")
        lines.append(f"effort: {role.effort}")
    return lines


def skills_line(skills: tuple[str, ...], harness: Harness) -> list[str]:
    """A `skills:` line, or none; formatted like the harness's `tools:` line."""
    if not skills:
        return []
    names = ", ".join(skills)
    return [f"skills: [{names}]" if harness.key == "agy" else f"skills: {names}"]


def stand_in_lines(role: Role, stand_in: str | None) -> tuple[str, str, tuple[str, ...]]:
    """The marker source, `name` and description lines for a role, or for its stand-in."""
    if stand_in is None:
        return "", role.name, role.description
    if not STAND_IN.fullmatch(stand_in):
        raise RoleError(f"stand-in name {stand_in!r} must be lower-case letters, digits and -")
    note = f"  It stands in for a plugin agent of this name: routewise's {role.name} role."
    return f"{AS}{stand_in}.md", stand_in, (*role.description, note)


def skill_list(skills: tuple[str, ...]) -> str:
    """The role's skills by name, so the agent looks for these and no others (spec R8)."""
    return ", ".join(f"`{name}`" for name in skills) or "none"


def checklist_form(skills: tuple[str, ...]) -> str:
    """The exact first line of the return: one `none` form only for a role without skills."""
    if not skills:
        return "`Checklist: none`."
    marks = ", ".join(f"{name} <loaded or missing>" for name in skills)
    rule = "`loaded` when that skill's full text was given to you with your task, else `missing`"
    return f"`Checklist: {marks}`: {rule}."


def render(
    role: Role,
    harness: Harness,
    source_label: str,
    command: str = "routewise/install",
    stand_in: str | None = None,
) -> str:
    tools = ", ".join(harness_tools(role, harness))
    # cc reads a comma-separated string; agy needs a YAML list.
    tools_line = f"tools: [{tools}]" if harness.key == "agy" else f"tools: {tools}"
    suffix, name, description = stand_in_lines(role, stand_in)
    front = [
        MARKER.format(source=source_label + suffix, command=command),
        f"name: {name}",
        *description,
        tools_line,
        *model_lines(role, harness),
        *skills_line(role.skills, harness),
    ]
    body = role.body.replace("{{skills}}", skill_list(role.skills))
    body = body.replace("{{checklist}}", checklist_form(role.skills))
    return "---\n" + "\n".join(front) + "\n---\n" + body


def is_generated(path: Path) -> bool:
    """True when the file's marker names a file of the same name: its role file, or for a
    stand-in the name after `as` (spec R9).

    A copy renamed by the user (strict-reviewer.md from reviewer.md) keeps a marker that
    names reviewer.md, so it counts as the user's file and is never rewritten or deleted.
    """
    head = path.read_text(encoding="utf-8", errors="replace")[:400]
    match = MARKER_LINE.match(head)
    return bool(match) and Path(match.group(1).rsplit(AS, 1)[-1]).name == path.name
