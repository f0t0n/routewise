"""ROUTING-BINDING.md is rendered from the shipped roles and routewise.toml [binding] (R14)."""

from dataclasses import replace
from pathlib import Path

import pytest
from binding import BindingError, is_generated, marker, render, rules_version

from roles import read_roles
from settings import Binding

HOME = Path(__file__).resolve().parent.parent
TEMPLATE = (HOME / "templates" / "binding.md").read_text(encoding="utf-8")
ROLES = read_roles(HOME / "roles")
VALUES = {
    "{{spec}}": "routewise/spec/SPEC-model-routing.md",
    "{{install}}": "routewise/install",
    "{{roles}}": "routewise/roles/",
    "{{harness}}": "routewise/harness.toml",
    "{{miss_log}}": "routewise/bin/miss-log",
    "{{agent_dirs}}": "`.claude/agents/` (cc)",
    "{{template}}": "routewise/templates/binding.md",
    "{{tier_map}}": "`fast` → `haiku`, `balanced` → `sonnet`, "
    "`deep` → `opus`, `frontier` → `fable`",
}
APPROVED = Binding("Ann (maintainer)", "2026-11-18", 4, "not an assistant project", "2026-12-02")


def text(binding: Binding = APPROVED, roles=ROLES, version: int = 4) -> str:
    return render(TEMPLATE, VALUES, roles, binding, version)


def test_first_line_is_the_marker_spelled_for_the_project():
    first = text().splitlines()[0]

    assert first == marker("routewise/templates/binding.md", "routewise/install")
    assert first.startswith("<!-- generated by routewise from routewise/templates/binding.md")
    assert first.endswith("re-run routewise/install -->")
    assert is_generated(text())
    assert not is_generated("# Binding: model routing in this project\n")
    assert "{{" not in text()


def test_one_row_per_role_from_its_tier_and_effort():
    rows = [x for x in text().splitlines() if x.startswith("| `")]

    assert len(rows) == len(ROLES)
    assert "| `judge` | `frontier` at `medium` |" in text()
    assert "| `auditor` | `deep` at `high` |" in text()
    assert "| `Explore` | `fast` at the harness's default effort |" in text()


def test_a_new_role_and_a_changed_tier_change_the_rows():
    extra = replace(ROLES[0], name="planner", tier="deep", effort="low")
    moved = [replace(r, tier="deep") if r.name == "reviewer" else r for r in ROLES]

    assert "| `planner` | `deep` at `low` |" in text(roles=[*ROLES, extra])
    assert "| `reviewer` | `deep` at `medium` |" in text(roles=moved)


def test_an_approval_for_the_shipped_version_is_shown():
    out = text()

    assert "Approved by Ann (maintainer) on 2026-11-18 for rules spec version 4." in out
    assert "pending" not in out and "not recorded" not in out
    assert "not an assistant project" in out
    assert "First review on 2026-12-02, then monthly." in out


def test_an_older_approval_is_pending_and_marks_frontier_rows():
    out = text(replace(APPROVED, approved_rules_version=3))

    assert "**Approval pending:** rules spec version 4 (approved: 3)." in out
    assert "| `judge` | `frontier` at `medium` (approval pending) |" in out
    assert "| `auditor` | `deep` at `high` |" in out


def test_no_approval_is_not_recorded():
    out = text(Binding())

    assert "**Approval not recorded.**" in out
    assert "| `judge` | `frontier` at `medium` (approval not recorded) |" in out
    assert "| Assistant model and effort pins (A3) | _Not recorded._ |" in out
    assert "| Miss-log review (M1) | _Not recorded._ |" in out


def test_an_approval_newer_than_the_shipped_spec_is_refused():
    with pytest.raises(BindingError, match="approved_rules_version 5 is newer") as caught:
        text(replace(APPROVED, approved_rules_version=5))
    assert "set it to 4" not in str(caught.value)
    assert "the version the person approved" in str(caught.value)


def test_rules_version_is_read_from_the_shipped_spec():
    spec = (HOME / "spec" / "SPEC-model-routing.md").read_text(encoding="utf-8")

    assert rules_version(spec) >= 4
    with pytest.raises(BindingError, match="no version line"):
        rules_version("# Spec\n\nno version here\n")


def test_values_are_never_expanded_again():
    """A value holding a placeholder stays text (settings refuses `{{`; render is one pass)."""
    pins = replace(APPROVED, assistant_pins="pins {{role_rows}}")

    out = text(pins)

    assert "| Assistant model and effort pins (A3) | pins {{role_rows}} |" in out


def test_not_recorded_never_names_the_shipped_version_as_the_one_to_set():
    out = text(Binding())

    assert "approved_rules_version = 4" not in out
    assert "only to the version the person approved" in out


def test_the_tier_map_is_rendered_with_overrides():
    values = {**VALUES, "{{tier_map}}": "`fast` → `claude-haiku-5-5`"}

    out = render(TEMPLATE, values, ROLES, APPROVED, 4)

    assert "Claude Code: `fast` → `claude-haiku-5-5`." in out


def test_a_version_without_a_name_is_no_approval():
    """Audit round 3: a version alone (say, copied from template text) approves nothing."""
    out = text(replace(APPROVED, approved_by=""))

    assert "**Approval not recorded.**" in out
    assert "| `judge` | `frontier` at `medium` (approval not recorded) |" in out
